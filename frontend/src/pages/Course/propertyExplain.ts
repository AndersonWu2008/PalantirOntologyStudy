const sleeves: Record<string, string> = {
  bull: '牛市这一套',
  highVol: '高波动这一套',
  sideways: '震荡这一套',
  bear: '熊市这一套',
};

const sleeveField: Record<string, string> = {
  StopLoss: '跌到成本的多少就该卖',
  TrailingActivate: '盈利到这个比例，才开始从高点跟踪',
  TrailingStop: '从买进以来的高点回落多少就卖',
  MaxHoldDays: '最多拿多少天，到期就卖',
  MaxPositions: '最多同时拿几只',
  SinglePositionPct: '单只最多占多少资金',
  MinScore: '分数低于这个就不买',
  AtrMultiple: '用入场时的波动大小放大止损距离',
};

function sleeveNote(apiName: string): string | null {
  for (const [prefix, label] of Object.entries(sleeves)) {
    if (!apiName.startsWith(prefix)) continue;
    const rest = apiName.slice(prefix.length);
    const field = sleeveField[rest];
    if (!field) continue;
    return `${label}：${field}。这是这一版规矩上的数。换规矩就新建一个做法，不改这里。`;
  }
  return null;
}

export function explainProperty(typeName: string, apiName: string): string {
  return fixed[typeName]?.[apiName] ?? (typeName === 'Strategy' ? sleeveNote(apiName) : null) ?? '';
}
